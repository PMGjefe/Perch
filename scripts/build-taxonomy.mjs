// Builds the bundled species taxonomy from the eBird/Clements CSV.
// Input : scripts/ebird-taxonomy-v2025.csv (eBird taxonomy v2025, via the auk R package)
// Output: assets/taxonomy/species.json          (app bundle, type-ahead search)
//         supabase/migrations/0002_species_data.sql (server copy)
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('./ebird-taxonomy-v2025.csv', import.meta.url), 'utf8');

function parseCsv(text) {
  const rows = [];
  let row = [], field = '', inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else inQuotes = false;
      } else field += c;
    } else if (c === '"') inQuotes = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const [header, ...rows] = parseCsv(src);
const col = (name) => header.indexOf(name);
const iCode = col('species_code'), iSci = col('scientific_name'), iCom = col('common_name');
const iFam = col('family'), iFamCom = col('family_common'), iCat = col('category'), iOrd = col('taxonomic_order');

const species = rows
  .filter((r) => r[iCat] === 'species' && r[iCode])
  .map((r) => ({
    code: r[iCode],
    common: r[iCom],
    sci: r[iSci],
    family: r[iFamCom] || r[iFam],
    familySci: r[iFam],
    order: Number(r[iOrd]),
  }))
  .sort((a, b) => a.order - b.order);

writeFileSync(new URL('../assets/taxonomy/species.json', import.meta.url), JSON.stringify(species));

const esc = (s) => `'${String(s).replace(/'/g, "''")}'`;
const chunks = [];
for (let i = 0; i < species.length; i += 500) {
  const values = species.slice(i, i + 500)
    .map((s) => `(${esc(s.code)},${esc(s.common)},${esc(s.sci)},${esc(s.familySci)},${esc(s.family)},${s.order})`)
    .join(',\n');
  chunks.push(`insert into public.species (code, common_name, scientific_name, family, family_common, taxonomic_order) values\n${values}\non conflict (code) do update set common_name = excluded.common_name, scientific_name = excluded.scientific_name, family = excluded.family, family_common = excluded.family_common, taxonomic_order = excluded.taxonomic_order;`);
}
writeFileSync(
  new URL('../supabase/migrations/0002_species_data.sql', import.meta.url),
  `-- Generated by scripts/build-taxonomy.mjs from the eBird/Clements taxonomy v2025. Do not edit by hand.\n${chunks.join('\n\n')}\n`,
);
console.log(`wrote ${species.length} species`);
